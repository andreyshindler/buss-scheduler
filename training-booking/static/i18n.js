let currentLang = localStorage.getItem('lang') || 'he';
let currentDir = currentLang === 'he' ? 'rtl' : 'ltr';

function t(key, vars) {
  let str = (TRANSLATIONS[currentLang] || TRANSLATIONS.he)[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, v);
    });
  }
  return str;
}

function applyLang(lang) {
  if (lang) currentLang = lang;
  currentDir = currentLang === 'he' ? 'rtl' : 'ltr';
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentDir;
  localStorage.setItem('lang', currentLang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });

  const btn = document.getElementById('lang-toggle');
  if (btn) btn.textContent = t('lang_toggle');
}

function toggleLang() {
  currentLang = currentLang === 'he' ? 'en' : 'he';
  applyLang(currentLang);
  if (window.onLangChange) window.onLangChange(currentLang);
}
